import { SEVERITIES, CATEGORIES, APP_NAME } from '@/lib/constants';
import { sortFindings, countBySeverity, scoreGrade } from '@/lib/scoring';

/**
 * Report exporters.
 *
 * jsPDF, JSZip and file-saver are all imported dynamically — together they are
 * roughly 400KB, and most sessions never export anything. Loading them on
 * click keeps them out of the workspace's initial bundle.
 */

const stamp = () => new Date().toISOString().slice(0, 10);

async function save(blob, filename) {
  const { saveAs } = await import('file-saver');
  saveAs(blob, filename);
}

/* ------------------------------------------------------------------ JSON -- */

export async function exportJson(review) {
  const payload = {
    generatedBy: APP_NAME,
    generatedAt: new Date().toISOString(),
    title: review.title,
    score: review.score,
    grade: scoreGrade(review.score).grade,
    mode: review.mode,
    model: review.model,
    profile: review.profile,
    summary: review.summary,
    verdict: review.done,
    counts: countBySeverity(review.findings),
    findings: sortFindings(review.findings),
  };

  await save(
    new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' }),
    `critiq-report-${stamp()}.json`
  );
}

/* ------------------------------------------------------------ Markdown -- */

export function buildMarkdown(review) {
  const findings = sortFindings(review.findings);
  const counts = countBySeverity(findings);
  const { grade, label } = scoreGrade(review.score);

  const lines = [
    `# Code review — ${review.title}`,
    '',
    `**Score:** ${review.score}/100 (${grade} — ${label})`,
    `**Findings:** ${findings.length}`,
    `**Reviewed:** ${new Date(review.createdAt).toLocaleString()}`,
    review.model ? `**Model:** ${review.model}` : `**Engine:** local analysis`,
    '',
    '## Severity breakdown',
    '',
    '| Severity | Count |',
    '| --- | --- |',
    ...Object.entries(counts)
      .filter(([, n]) => n > 0)
      .map(([severity, n]) => `| ${SEVERITIES[severity].label} | ${n} |`),
    '',
  ];

  if (review.summary?.overview) {
    lines.push('## Summary', '', review.summary.overview, '');

    if (review.summary.strengths?.length) {
      lines.push('### What works', '', ...review.summary.strengths.map((s) => `- ${s}`), '');
    }
  }

  lines.push('## Findings', '');

  findings.forEach((finding, index) => {
    lines.push(
      `### ${index + 1}. ${finding.title}`,
      '',
      `- **Severity:** ${SEVERITIES[finding.severity].label}`,
      `- **Category:** ${CATEGORIES[finding.category]?.label ?? finding.category}`,
      `- **Location:** \`${finding.file}${finding.line ? `:${finding.line}` : ''}\``,
      `- **Confidence:** ${finding.confidence}`,
      '',
      finding.description,
      ''
    );

    if (finding.impact) lines.push(`**Impact.** ${finding.impact}`, '');
    if (finding.suggestion) lines.push(`**Fix.** ${finding.suggestion}`, '');

    if (finding.codeBefore && finding.codeAfter) {
      lines.push(
        '```diff',
        ...finding.codeBefore.split('\n').map((l) => `- ${l}`),
        ...finding.codeAfter.split('\n').map((l) => `+ ${l}`),
        '```',
        ''
      );
    }
  });

  if (review.done?.verdict) {
    lines.push('## Verdict', '', review.done.verdict, '');
    if (review.done.topPriorities?.length) {
      lines.push('**Fix first:**', '', ...review.done.topPriorities.map((p) => `1. ${p}`), '');
    }
  }

  lines.push('---', '', `Generated by ${APP_NAME}.`);
  return lines.join('\n');
}

export async function exportMarkdown(review) {
  await save(
    new Blob([buildMarkdown(review)], { type: 'text/markdown;charset=utf-8' }),
    `critiq-report-${stamp()}.md`
  );
}

/* ----------------------------------------------------------------- PDF -- */

export async function exportPdf(review) {
  const { default: jsPDF } = await import('jspdf');
  const { default: autoTable } = await import('jspdf-autotable');

  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 48;
  const contentWidth = pageWidth - margin * 2;

  const findings = sortFindings(review.findings);
  const counts = countBySeverity(findings);
  const { grade, label } = scoreGrade(review.score);

  /* cover block */
  doc.setFillColor(37, 99, 235);
  doc.rect(0, 0, pageWidth, 108, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.text('Code Review Report', margin, 52);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.text(review.title, margin, 74);
  doc.text(new Date(review.createdAt).toLocaleString(), margin, 90);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(30);
  doc.text(`${review.score}`, pageWidth - margin, 60, { align: 'right' });
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`${grade} — ${label}`, pageWidth - margin, 78, { align: 'right' });

  doc.setTextColor(30, 41, 59);
  let cursorY = 140;

  /* summary */
  if (review.summary?.overview) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.text('Summary', margin, cursorY);
    cursorY += 18;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    const wrapped = doc.splitTextToSize(review.summary.overview, contentWidth);
    doc.text(wrapped, margin, cursorY);
    cursorY += wrapped.length * 13 + 16;
  }

  /* severity table */
  autoTable(doc, {
    startY: cursorY,
    head: [['Severity', 'Count']],
    body: Object.entries(counts)
      .filter(([, n]) => n > 0)
      .map(([severity, n]) => [SEVERITIES[severity].label, String(n)]),
    theme: 'grid',
    headStyles: { fillColor: [37, 99, 235], fontSize: 9 },
    bodyStyles: { fontSize: 9 },
    margin: { left: margin, right: margin },
    tableWidth: 220,
  });

  cursorY = doc.lastAutoTable.finalY + 26;

  /* findings table */
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(`Findings (${findings.length})`, margin, cursorY);

  autoTable(doc, {
    startY: cursorY + 12,
    head: [['#', 'Severity', 'Category', 'Location', 'Finding']],
    body: findings.map((finding, index) => [
      String(index + 1),
      SEVERITIES[finding.severity].label,
      CATEGORIES[finding.category]?.label ?? finding.category,
      `${finding.file}${finding.line ? `:${finding.line}` : ''}`,
      `${finding.title}\n${finding.description}`,
    ]),
    theme: 'striped',
    headStyles: { fillColor: [37, 99, 235], fontSize: 9 },
    bodyStyles: { fontSize: 8, cellPadding: 5, valign: 'top' },
    columnStyles: {
      0: { cellWidth: 22 },
      1: { cellWidth: 52 },
      2: { cellWidth: 74 },
      3: { cellWidth: 96 },
    },
    margin: { left: margin, right: margin },
  });

  /* page numbers, added last so the total is known */
  const pageCount = doc.internal.getNumberOfPages();
  for (let page = 1; page <= pageCount; page += 1) {
    doc.setPage(page);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `${APP_NAME} · page ${page} of ${pageCount}`,
      pageWidth / 2,
      doc.internal.pageSize.getHeight() - 22,
      { align: 'center' }
    );
  }

  doc.save(`critiq-report-${stamp()}.pdf`);
}

/* ----------------------------------------------------------------- ZIP -- */

export async function exportZip(review) {
  const { default: JSZip } = await import('jszip');
  const zip = new JSZip();

  zip.file('REPORT.md', buildMarkdown(review));
  zip.file('findings.json', JSON.stringify(sortFindings(review.findings), null, 2));

  const src = zip.folder('src');
  review.files.forEach((file) => src.file(file.name, file.content));

  const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' });
  await save(blob, `critiq-review-${stamp()}.zip`);
}
